#!/usr/bin/env python3
"""
Plot spline trajectory data from CSV file

This script reads the CSV file generated by spline_example.cpp and creates
visualization plots for the spline trajectory.

Authors: Rafael Pérez Seguí, Carmen De Rojas Pita-Romero
"""

import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
import argparse
import os


def _plot_spline_trajectory(theta, px, py, pz, vx, vy, vz, 
                           title: str, param_label: str, colormap: str):
    """
    Internal function to plot spline trajectory data
    
    Args:
        theta: Parameter values (theta or arc-length)
        px, py, pz: Position components
        vx, vy, vz: Velocity components
        title: Figure title
        param_label: Label for the parameter axis
        colormap: Colormap to use for plots
    """
    # Compute velocity magnitude
    v_mag = np.sqrt(vx**2 + vy**2 + vz**2)
    
    # Create figure with subplots
    fig = plt.figure(figsize=(16, 12))
    fig.suptitle(title, fontsize=16, fontweight='bold')
    
    # 1. 3D trajectory
    ax1 = fig.add_subplot(2, 3, 1, projection='3d')
    scatter = ax1.scatter(px, py, pz, c=v_mag, cmap=colormap, s=10, alpha=0.6)
    ax1.plot(px, py, pz, '-', alpha=0.3, linewidth=1)
    # Mark start and end points
    ax1.scatter([px[0]], [py[0]], [pz[0]], c='green', s=100, marker='o', 
                edgecolors='black', linewidths=2, label='Start', zorder=5)
    ax1.scatter([px[-1]], [py[-1]], [pz[-1]], c='red', s=100, marker='s', 
                edgecolors='black', linewidths=2, label='End', zorder=5)
    ax1.set_xlabel('X [m]')
    ax1.set_ylabel('Y [m]')
    ax1.set_zlabel('Z [m]')
    ax1.set_title('3D Spline Trajectory')
    ax1.legend()
    plt.colorbar(scatter, ax=ax1, label='Velocity [m/s]', shrink=0.5)
    ax1.grid(True)
    
    # Set equal aspect ratio for 3D plot
    max_range = np.array([px.max()-px.min(), py.max()-py.min(), pz.max()-pz.min()]).max() / 2.0
    mid_x = (px.max()+px.min()) * 0.5
    mid_y = (py.max()+py.min()) * 0.5
    mid_z = (pz.max()+pz.min()) * 0.5
    ax1.set_xlim(mid_x - max_range, mid_x + max_range)
    ax1.set_ylim(mid_y - max_range, mid_y + max_range)
    ax1.set_zlim(mid_z - max_range, mid_z + max_range)
    
    # 2. XY plane (top view)
    ax2 = fig.add_subplot(2, 3, 2)
    scatter2 = ax2.scatter(px, py, c=v_mag, cmap=colormap, s=20, alpha=0.6)
    ax2.plot(px, py, '-', alpha=0.3, linewidth=1)
    # Mark start and end points
    ax2.scatter([px[0]], [py[0]], c='green', s=100, marker='o', 
                edgecolors='black', linewidths=2, label='Start', zorder=5)
    ax2.scatter([px[-1]], [py[-1]], c='red', s=100, marker='s', 
                edgecolors='black', linewidths=2, label='End', zorder=5)
    ax2.set_xlabel('X [m]')
    ax2.set_ylabel('Y [m]')
    ax2.set_title('XY Plane (Top View)')
    ax2.grid(True)
    ax2.axis('equal')
    ax2.legend()
    plt.colorbar(scatter2, ax=ax2, label='Velocity [m/s]')
    
    # 3. XZ plane (side view)
    ax3 = fig.add_subplot(2, 3, 3)
    scatter3 = ax3.scatter(px, pz, c=v_mag, cmap=colormap, s=20, alpha=0.6)
    ax3.plot(px, pz, '-', alpha=0.3, linewidth=1)
    # Mark start and end points
    ax3.scatter([px[0]], [pz[0]], c='green', s=100, marker='o', 
                edgecolors='black', linewidths=2, label='Start', zorder=5)
    ax3.scatter([px[-1]], [pz[-1]], c='red', s=100, marker='s', 
                edgecolors='black', linewidths=2, label='End', zorder=5)
    ax3.set_xlabel('X [m]')
    ax3.set_ylabel('Z [m]')
    ax3.set_title('XZ Plane (Side View)')
    ax3.grid(True)
    ax3.axis('equal')
    ax3.legend()
    plt.colorbar(scatter3, ax=ax3, label='Velocity [m/s]')
    
    # 4. Position components
    ax4 = fig.add_subplot(2, 3, 4)
    ax4.plot(theta, px, 'r-', label='px', linewidth=2)
    ax4.plot(theta, py, 'g-', label='py', linewidth=2)
    ax4.plot(theta, pz, 'b-', label='pz', linewidth=2)
    ax4.set_xlabel(param_label)
    ax4.set_ylabel('Position [m]')
    ax4.set_title(f'Position Components vs {param_label}')
    ax4.legend()
    ax4.grid(True)
    
    # 5. Velocity components
    ax5 = fig.add_subplot(2, 3, 5)
    ax5.plot(theta, vx, 'r-', label='vx', linewidth=2)
    ax5.plot(theta, vy, 'g-', label='vy', linewidth=2)
    ax5.plot(theta, vz, 'b-', label='vz', linewidth=2)
    ax5.set_xlabel(param_label)
    ax5.set_ylabel('Velocity [m/s]')
    ax5.set_title(f'Velocity Components vs {param_label}')
    ax5.legend()
    ax5.grid(True)
    
    # 6. Velocity magnitude
    ax6 = fig.add_subplot(2, 3, 6)
    ax6.plot(theta, v_mag, '-', linewidth=2)
    ax6.set_xlabel(param_label)
    ax6.set_ylabel('|v| [m/s]')
    ax6.set_title(f'Velocity Magnitude vs {param_label}')
    ax6.grid(True)
    ax6.axhline(y=v_mag.mean(), color='r', linestyle='--', 
                label=f'Mean: {v_mag.mean():.2f} m/s')
    ax6.legend()
    
    plt.tight_layout()
    
    return v_mag


def plot_theta_spline_data(csv_file: str, block: bool = True):
    """
    Plot theta-parametrized spline trajectory data from CSV file
    
    Args:
        csv_file: Path to the CSV file with theta-parametrized spline data
        block: If True, block execution until window is closed
    """
    # Read CSV file
    if not os.path.exists(csv_file):
        print(f"Error: File {csv_file} not found")
        return
    
    print(f"Reading data from {csv_file}...")
    df = pd.read_csv(csv_file)
    
    # Extract data
    theta = df['theta'].values
    px = df['px'].values
    py = df['py'].values
    pz = df['pz'].values
    vx = df['vx'].values
    vy = df['vy'].values
    vz = df['vz'].values
    
    print(f"Loaded {len(theta)} data points")
    print(f"Theta range: [{theta.min():.3f}, {theta.max():.3f}]")
    
    # Plot trajectory
    v_mag = _plot_spline_trajectory(
        theta, px, py, pz, vx, vy, vz,
        title='Theta-Parametrized Spline Trajectory',
        param_label='Theta',
        colormap='viridis'
    )
    
    if block:
        plt.show()
    
    # Print statistics
    print("\n=== Theta-Parametrized Trajectory Statistics ===")
    print(f"Total theta range: {theta.max():.3f}")
    print("Position range:")
    print(f"  X: [{px.min():.3f}, {px.max():.3f}] m")
    print(f"  Y: [{py.min():.3f}, {py.max():.3f}] m")
    print(f"  Z: [{pz.min():.3f}, {pz.max():.3f}] m")
    print("Velocity magnitude:")
    print(f"  Mean: {v_mag.mean():.3f} m/s")
    print(f"  Min: {v_mag.min():.3f} m/s")
    print(f"  Max: {v_mag.max():.3f} m/s")
    print(f"  Std: {v_mag.std():.3f} m/s")


def plot_arc_spline_data(csv_file: str, block: bool = True):
    """
    Plot arc-length parametrized spline trajectory data from CSV file
    
    Args:
        csv_file: Path to the CSV file with arc-length parametrized spline data
        block: If True, block execution until window is closed
    """
    # Read CSV file
    if not os.path.exists(csv_file):
        print(f"Error: File {csv_file} not found")
        return
    
    print(f"Reading arc-length data from {csv_file}...")
    df = pd.read_csv(csv_file)
    
    # Extract data (arc-length parameter stored as 's' in CSV)
    s = df['theta'].values
    px = df['px'].values
    py = df['py'].values
    pz = df['pz'].values
    vx = df['vx'].values
    vy = df['vy'].values
    vz = df['vz'].values
    
    print(f"Loaded {len(s)} data points")
    print(f"Arc-length range: [{s.min():.3f}, {s.max():.3f}]")
    
    # Determine method from filename
    method_name = "Arc-Length Reparametrization"
    if 'trajectory' in csv_file.lower():
        method_name = "Spline Trajectory Generator"
    
    # Plot trajectory
    v_mag = _plot_spline_trajectory(
        s, px, py, pz, vx, vy, vz,
        title=f'Arc-Length Parametrized Spline Trajectory ({method_name})',
        param_label='Arc-length [m]',
        colormap='plasma'
    )
    
    if block:
        plt.show()
    
    # Print statistics
    print("\n=== Arc-Length Parametrized Trajectory Statistics ===")
    print(f"Total arc length: {s.max():.3f}")
    print("Position range:")
    print(f"  X: [{px.min():.3f}, {px.max():.3f}] m")
    print(f"  Y: [{py.min():.3f}, {py.max():.3f}] m")
    print(f"  Z: [{pz.min():.3f}, {pz.max():.3f}] m")
    print("Velocity magnitude:")
    print(f"  Mean: {v_mag.mean():.3f} m/s")
    print(f"  Min: {v_mag.min():.3f} m/s")
    print(f"  Max: {v_mag.max():.3f} m/s")
    print(f"  Std: {v_mag.std():.3f} m/s")


def main():
    parser = argparse.ArgumentParser(
        description='Plot spline trajectory data from CSV file')
    parser.add_argument(
        '--input', '-i',
        type=str,
        default='spline_theta.csv',
        help='Input CSV file for theta-parametrized data (default: spline_theta.csv)')
    parser.add_argument(
        '--arc-input', '-a',
        type=str,
        default='spline_arc_length.csv',
        help='Input CSV file for arc-length parametrized data (default: spline_arc_length.csv)')
    parser.add_argument(
        '--traj-input', '-t',
        type=str,
        default='spline_trajectory_generator.csv',
        help='Input CSV file for trajectory generator data (default: spline_trajectory_generator.csv)')
    
    args = parser.parse_args()
    
    # Plot theta-parametrized data
    if os.path.exists(args.input):
        plot_theta_spline_data(args.input, block=False)
    
    # # Plot arc-length parametrized data if file exists
    # if os.path.exists(args.arc_input):
    #     plot_arc_spline_data(args.arc_input, block=False)
        
    # Plot trajectory generator data if file exists
    if os.path.exists(args.traj_input):
        plot_arc_spline_data(args.traj_input, block=False)
    
    # Show all figures at once
    plt.show()


if __name__ == '__main__':
    main()
